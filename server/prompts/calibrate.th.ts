export function buildCalibratePrompt(descriptions: string[], mustCoverAll: boolean) {
  return `คุณคือผู้ช่วยจัดระเบียบชื่อรายการ (description) ในระบบบันทึกรายรับ-รายจ่าย

นี่คือชื่อรายการที่ต้องวิเคราะห์ (ไม่ซ้ำกัน):
${descriptions.map((d) => `- ${d}`).join('\n')}

หน้าที่ของคุณ: วิเคราะห์ลิสต์นี้ แล้วเสนอกลุ่มการเปลี่ยนแปลงเฉพาะจุดที่ควรแก้จริง ๆ เช่น:
- คำที่สะกด/เขียนต่างกันแต่หมายถึงของเดียวกัน (เช่น "น้ำแพ็ค 1.5" กับ "น้ำแพ็ค1.5ลิตร") — รวมเป็นคำเดียว
- คำที่หลุดเป็นภาษาอังกฤษทั้งที่ควรเป็นภาษาไทย (เช่น "Medicine" ควรเป็น "ค่ายา") — แก้เป็นภาษาไทย
- คำที่เขียนไม่เรียบร้อย/มีคำฟุ่มเฟือยเกินจำเป็น — เกลาให้กระชับขึ้น

${
  mustCoverAll
    ? '**ทุกคำในลิสต์ต้องปรากฏอยู่ใน "olds" ของกลุ่มใดกลุ่มหนึ่งเสมอ** ถ้าคำไหนไม่มีอะไรต้องแก้ ให้ตั้ง "new" เท่ากับคำเดิมนั้นเลย (กลุ่ม 1 คำ ไม่มีการเปลี่ยนแปลง) ห้ามละคำไหนไปเฉย ๆ'
    : '**ห้ามเสนอกลุ่มถ้าไม่มีอะไรต้องแก้จริง ๆ** ปล่อยคำที่โอเคอยู่แล้วไว้เฉย ๆ ไม่ต้องเอาเข้าลิสต์เลย (ไม่ต้องเสนอให้ครบทุกคำ)'
}

กติกาสำคัญมาก:
- ทุกคำใน "olds" ต้องคัดลอกมาจากลิสต์ด้านบนเป๊ะทุกตัวอักษร ห้ามพิมพ์ผิดหรือแก้แม้แต่นิดเดียว (ระบบจะเอาไปจับคู่แบบ exact match)
- "new" ต้องเป็นภาษาไทยเสมอ ห้ามแปลเป็นอังกฤษเด็ดขาด ยกเว้นชื่อเฉพาะ/แบรนด์สากลที่เขียนทับศัพท์เป็นอังกฤษอยู่แล้วจริง ๆ เช่น "ค่ายา" ต้องเป็น "ค่ายา" ห้ามเป็น "Medicine"
- กลุ่มหนึ่งมี "olds" ได้ตั้งแต่ 1 คำขึ้นไป (1 คำ = แก้/ยืนยันคำเดียวเดี่ยว ๆ ไม่ใช่การรวม)
- ตอบเป็น JSON ล้วนเท่านั้น ห้ามมีข้อความอื่นปน

โครงสร้าง JSON ที่ต้องตอบกลับ:
{
  "groups": [
    { "new": string, "olds": string[] }
  ]
}`
}
