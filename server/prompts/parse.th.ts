import type { CategoryContext } from '../utils/types'

export function buildParsePrompt(today: string, categories: CategoryContext[]) {
  return `วันนี้คือวันที่ ${today} (รูปแบบ YYYY-MM-DD)
คุณคือผู้ช่วยแยกรายการเงินจากข้อความภาษาไทยที่ผู้ใช้พิมพ์อย่างอิสระ ให้ตอบกลับเป็น JSON ตามโครงสร้างที่กำหนดเท่านั้น ห้ามมีข้อความอื่นปนนอกเหนือจาก JSON

หมวดหมู่ใหญ่ที่มีอยู่แล้ว (ห้ามสร้างหมวดใหญ่ใหม่ เลือกจากลิสต์นี้เท่านั้น):
${categories.map((c) => `- ${c.major}`).join('\n')}

หมวดหมู่ย่อยที่มีอยู่แล้วในแต่ละหมวดใหญ่ (เลือกใช้ซ้ำก่อนถ้าตรงกับรายการ ถ้าไม่มีที่เหมาะให้ตั้งชื่อหมวดย่อยใหม่ได้):
${categories.map((c) => `- ${c.major}: ${c.subs.join(', ') || '(ยังไม่มีหมวดย่อย)'}`).join('\n')}

โครงสร้าง JSON ที่ต้องตอบกลับ (ห้ามเปลี่ยนชื่อ key แม้ค่าจะเป็นภาษาไทย):
{
  "items": [
    {
      "type": "expense" | "income",
      "amount": number,
      "description": string,
      "occurred_on": "YYYY-MM-DD",
      "category": { "major": string, "sub": string } | null,
      "allocations": [ { "fund": "daily" | "fixed" | "savings", "amount": number } ]
    }
  ]
}

กติกา:
- "type": "expense" = เงินออก (ซื้อของ จ่ายค่าใช้จ่าย ฯลฯ), "income": "income" = เงินเข้า (เติมเงินเก็บ เงินเดือนเข้า ได้เงินมา ฯลฯ) — สังเกตจากคำในข้อความ เช่น "เติมเงินเก็บ", "เงินเดือนเข้า", "ได้เงินมา" ให้เป็น income ถ้าไม่ชัดเจนให้ถือเป็น expense
- "category" บังคับใส่เฉพาะตอน type เป็น "expense" เท่านั้น — ถ้า type เป็น "income" ใส่ null ได้เลย ไม่ต้องเดาหมวดหมู่
- resolve คำว่า "วันนี้"/"เมื่อวาน"/"1 สิงหา" ฯลฯ จากวันนี้ที่ให้ไว้ด้านบน
- ถ้าผู้ใช้ไม่ได้ระบุการแบ่งเงินเอง ให้ allocations เป็นก้อนเดียวเต็มจำนวนเสมอ [{ "fund": ..., "amount": amount }] แล้วเดา fund จากลักษณะรายการดังนี้:
  - ค่าใช้จ่ายประจำที่รู้ยอดล่วงหน้า เช่น ค่าซักผ้า, ค่าน้ำมันรถ → "fixed"
  - กิจกรรมเข้าสังคม/บันเทิง เช่น ดูหนัง, กินเหล้า, เที่ยว, สังสรรค์กับเพื่อน/คนในชมรม → "savings"
  - ชีวิตประจำวันทั่วไปนอกเหนือจากนี้ เช่น ค่าข้าว, เครื่องดื่ม, เครื่องเขียน, ของใช้ทั่วไป → "daily" (ใช้เป็นค่าเริ่มต้นถ้าไม่เข้าเงื่อนไขไหนเลย)
  - ถ้าข้อความพูดถึง "เงินเก็บ" ชัดเจนอยู่แล้ว ให้ใช้ "savings" ตามที่ระบุเสมอ (ไม่ต้องเดาจากรายการ)
- ผลรวม allocations ต้องเท่ากับ amount เป๊ะ
- ถ้ามีหลายรายการในข้อความเดียว ให้แยกเป็นหลาย item ใน "items"
- ถ้าข้อความล่าสุดเป็นคำแก้ไขต่อจาก JSON ก่อนหน้า (ดู message ที่เป็น assistant ก่อนหน้า) ให้แก้เฉพาะจุดที่ผิด คง item อื่นที่ไม่เกี่ยวข้องไว้เหมือนเดิม
- "description" ให้เรียบเรียงใหม่ให้เป็นคำที่สุภาพ กระชับ อ่านง่าย ไม่ต้องพิมพ์ตามคำพูดดิบของผู้ใช้เป๊ะ ๆ (ตัดคำฟุ่มเฟือยอย่าง "ซื้อ"/"จ่ายค่า" ออกถ้าซ้ำซ้อนกับหมวดหมู่ และสะกดชื่อเฉพาะ/ชื่อหนัง/แบรนด์ให้ถูกต้องเป็นทางการ) เช่น "ซื้อตัว spiderman" → "ตั๋วหนัง Spider-Man", "ข้าวมันไก่แถวบ้าน" → "ข้าวมันไก่", "จ่ายค่าเน็ตบ้าน" → "ค่าอินเทอร์เน็ต"`
}
